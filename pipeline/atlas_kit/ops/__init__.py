"""Python mirrors of the TS CORE_OPS (site/src/lib/atlas/ops/*.ts).

Each mirror module declares the same metadata the TS OpDef does (OP, VERSION, ATTRS, ALIASES, WEIGHTS, SUBS, plus a
bilingual LABEL used as the default layer label) and a `reference(xs, params, weights)` that computes the PyTorch
value for one layer (or `(value, {sub: tensor})` for ops with sub-steps, such as lstm). All 20 CORE_OPS have a mirror
(W1-E1: input, linear, relu, tanh, sigmoid; W1-E2: the other 15). `compare_with_manifest()` checks every mirror's
metadata against ops.json, and atlas_kit/tests/test_mirrors.py checks every reference against the torch goldens and
the TS ops (design §8.2 W1-E2 acceptance 2).

Attributes are validated against site/src/lib/atlas/schema/ops.json (generated by W1-A from the TS OpDefs:
`node src/lib/atlas/ops/manifest.ts --write`). When that file does not exist yet, the mirror's own ATTRS are used
and a note is recorded once. Unknown or missing attributes raise AK106.
"""
from __future__ import annotations

import json
from pathlib import Path
from types import ModuleType
from typing import Any, Optional

from ..errors import fail
from . import (add as _add, attention_mix as _attention_mix, attention_scores as _attention_scores,
               causal_mask as _causal_mask, concat as _concat, conv2d as _conv2d, embedding as _embedding,
               flatten as _flatten, gelu as _gelu, input as _input, layernorm as _layernorm, linear as _linear,
               lstm as _lstm, maxpool2d as _maxpool2d, position_embedding as _position_embedding, relu as _relu,
               sigmoid as _sigmoid, silu as _silu, softmax as _softmax, tanh as _tanh)

# CORE_OPS order (site/src/lib/atlas/ops/index.ts)
MIRRORS: dict[str, ModuleType] = {m.OP: m for m in (
    _input, _conv2d, _linear, _relu, _tanh, _sigmoid, _silu, _gelu, _maxpool2d, _flatten, _concat, _add, _embedding,
    _position_embedding, _layernorm, _attention_scores, _causal_mask, _softmax, _attention_mix, _lstm)}

_ATTR_TYPES = ("int", "float", "bool", "string", "int[]", "float[]")
_manifest_cache: dict[str, Optional[dict]] = {}
NOTES: list[str] = []


def _note(msg: str) -> None:
    if msg not in NOTES:
        NOTES.append(msg)


def manifest_path(site: Optional[Path] = None) -> Path:
    from ..paths import atlas_site
    return (site or atlas_site()) / "src" / "lib" / "atlas" / "schema" / "ops.json"


def load_manifest(site: Optional[Path] = None) -> Optional[dict]:
    """ops.json as {op: entry}, or None when it does not exist. Accepts a list of entries, {ops: [...]} or {op: entry}."""
    p = manifest_path(site)
    key = str(p)
    if key in _manifest_cache:
        return _manifest_cache[key]
    if not p.is_file():
        _manifest_cache[key] = None
        _note(f"{p.as_posix()} not found: attributes checked against the Python mirrors' own declarations")
        return None
    raw = json.loads(p.read_text(encoding="utf-8-sig"))
    entries = raw.get("ops", raw) if isinstance(raw, dict) else raw
    if isinstance(entries, dict):
        table = {k: dict(v, op=v.get("op", k)) for k, v in entries.items() if isinstance(v, dict)}
    else:
        table = {e["op"]: e for e in entries}
    _manifest_cache[key] = table
    return table


def clear_cache() -> None:
    _manifest_cache.clear()
    NOTES.clear()


def resolve(op: str, site: Optional[Path] = None) -> tuple[str, dict, Optional[dict], Optional[ModuleType]]:
    """(canonical op, alias params, ops.json entry or None, Python mirror or None) for an op name or alias."""
    table = load_manifest(site)
    if table is not None:
        if op in table:
            return op, {}, table[op], MIRRORS.get(op)
        for name, e in table.items():
            aliases = e.get("aliases") or {}
            if op in aliases:
                return name, dict(aliases[op] or {}), e, MIRRORS.get(name)
    if op in MIRRORS:
        return op, {}, None, MIRRORS[op]
    for name, m in MIRRORS.items():
        if op in getattr(m, "ALIASES", {}):
            return name, dict(m.ALIASES[op] or {}), None, m
    return op, {}, None, None


def _type_ok(t: str, v: Any) -> bool:
    if t == "int":
        return isinstance(v, int) and not isinstance(v, bool)
    if t == "float":
        return isinstance(v, (int, float)) and not isinstance(v, bool)
    if t == "bool":
        return isinstance(v, bool)
    if t == "string":
        return isinstance(v, str)
    if t == "int[]":
        return isinstance(v, (list, tuple)) and all(isinstance(x, int) and not isinstance(x, bool) for x in v)
    if t == "float[]":
        return isinstance(v, (list, tuple)) and all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in v)
    return True


def attr_decls(op: str, site: Optional[Path] = None) -> Optional[dict]:
    """The attribute declarations for an op (ops.json first, then the mirror), or None for an unknown (local) op."""
    canon, _, entry, mirror = resolve(op, site)
    if entry is not None:
        return dict(entry.get("attrs") or {})
    if mirror is not None:
        return dict(mirror.ATTRS)
    return None


def check_attrs(op: str, params: dict, *, where: str, site: Optional[Path] = None) -> dict:
    """Validate layer params against the op's declared attributes. Returns the params to write (unchanged).
    Unknown op (a local op without a declaration): returned unchanged; `atlas check` validates it against the TS op."""
    decls = attr_decls(op, site)
    if decls is None:
        return params
    src = "ops.json" if load_manifest(site) is not None and resolve(op, site)[2] is not None else "the Python mirror"
    unknown = [k for k in params if k not in decls]
    if unknown:
        fail("AK106", f"op {op!r}: unknown attribute(s) {', '.join(map(repr, unknown))}", where=where,
             likely=f"{src} declares only: {', '.join(sorted(decls)) or '(none)'}",
             fix="remove the attribute, or add it to the TS OpDef.attrs and regenerate schema/ops.json (W1-A manifest)")
    for k, d in decls.items():
        if k not in params and d.get("required") and "default" not in d:
            fail("AK106", f"op {op!r}: required attribute {k!r} is missing", where=where,
                 fix=f"pass {k}=... to the builder call")
        if k in params and not _type_ok(d.get("type", ""), params[k]):
            fail("AK106", f"op {op!r}: attribute {k!r} = {params[k]!r} is not of type {d.get('type')}", where=where)
    return params


def declared(op: str, attr: str, site: Optional[Path] = None) -> bool:
    d = attr_decls(op, site)
    return d is not None and attr in d


def compare_with_manifest(site: Optional[Path] = None) -> list[str]:
    """Differences between every Python mirror and ops.json (empty list = they agree). [] with a note if no ops.json."""
    table = load_manifest(site)
    if table is None:
        return []
    out: list[str] = []
    for name in table:
        if name not in MIRRORS:
            out.append(f"{name}: in ops.json but has no Python mirror")
    for name, m in MIRRORS.items():
        e = table.get(name)
        if e is None:
            out.append(f"{name}: in the Python mirrors but not in ops.json")
            continue
        if int(e.get("version", 1)) != int(m.VERSION):
            out.append(f"{name}: version {m.VERSION} (Python) vs {e.get('version')} (ops.json)")
        ja, pa = e.get("attrs") or {}, m.ATTRS
        for k in sorted(set(ja) | set(pa)):
            if k not in ja:
                out.append(f"{name}: attribute {k!r} only in the Python mirror")
            elif k not in pa:
                out.append(f"{name}: attribute {k!r} only in ops.json")
            else:
                for f in ("type", "default", "required"):
                    if ja[k].get(f) != pa[k].get(f):
                        out.append(f"{name}.{k}: {f} {pa[k].get(f)!r} (Python) vs {ja[k].get(f)!r} (ops.json)")
        jw = [(w["slot"], bool(w.get("optional"))) for w in (e.get("weights") or [])]
        pw = [(w["slot"], bool(w.get("optional"))) for w in m.WEIGHTS]
        if jw != pw:
            out.append(f"{name}: weights {pw} (Python) vs {jw} (ops.json)")
        if sorted((e.get("aliases") or {}).keys()) != sorted(m.ALIASES.keys()):
            out.append(f"{name}: aliases {sorted(m.ALIASES)} (Python) vs {sorted(e.get('aliases') or {})} (ops.json)")
        js = [s["name"] if isinstance(s, dict) else s for s in (e.get("subs") or [])]
        if js != list(m.SUBS):
            out.append(f"{name}: subs {list(m.SUBS)} (Python) vs {js} (ops.json)")
        for k, v in (e.get("aliases") or {}).items():
            if dict(v or {}) != dict(m.ALIASES.get(k) or {}):
                out.append(f"{name}: alias {k!r} params {m.ALIASES.get(k)!r} (Python) vs {v!r} (ops.json)")
        if "category" in e and getattr(m, "CATEGORY", e["category"]) != e["category"]:
            out.append(f"{name}: category {getattr(m, 'CATEGORY', None)!r} (Python) vs {e['category']!r} (ops.json)")
        lab = e.get("label") or {}
        if lab and tuple(getattr(m, "LABEL", ())) != (lab.get("en"), lab.get("zh")):
            out.append(f"{name}: label {getattr(m, 'LABEL', None)!r} (Python) vs {lab!r} (ops.json)")
    return out
