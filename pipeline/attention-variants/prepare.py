"""attention-variants: the evaluation text and the measured facts of the concept page.

1. Writes the live evaluation set (the same as the quantization page's): the first 4 stories of TinyStories' validation
   split (TinyGPT's own tokenized copy, pipeline/data/tinystories/val.bin) that are at least 65 tokens long, 65 tokens
   each, plus the probe prompt "Once upon a time, there was a little" (TinyGPT's replay.json probe 0), with the display
   text of every vocabulary id, to site/src/lib/explainers/attention-variants/evalset.ts (generated; do not edit).
2. Converts TinyGPT's trained multi-head attention to grouped-query attention with 2 key/value heads and to multi-query
   attention with 1, by mean pooling (gqa.py pool_kv), and uptrains each, with the MHA model as the control, for 1,500
   steps (5% of TinyGPT's 30,000 pretraining steps, the share Ainslie et al. 2023 uptrain with) on TinyStories' training
   tokens: AdamW (0.9, 0.95), weight decay 0.1 on matrices, batch 512 x 64 tokens, lr 6e-4 (TinyGPT's final learning
   rate) after 50 warm-up steps, cosine to 6e-5, grad clip 1.0, fp32, seed 0. Perplexity on 1,000 non-overlapping
   65-token windows of the validation split (64,000 next tokens) at steps 0, 50, 150, 500 and 1,500 goes to
   site/static/models/attention-variants/facts.json ({fact:<key>} in the narration).

    npm run atlas -- py pipeline/attention-variants/prepare.py      (about a minute on a GPU)
"""
from __future__ import annotations

import datetime
import json
import math
import sys
import time
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tinygpt"))
from gqa import DATA, GPT_DIR, SITE, forward, load_tinygpt, perplexity, pool_kv, windows  # noqa: E402
import bpe  # noqa: E402

LIVE_N, BIG_N = 4, 1000
STEPS, WARM, BATCH, LR, LR_END = 1500, 50, 512, 6e-4, 6e-5
EVAL_AT = [0, 50, 150, 500, 1500]
KVS = [4, 2, 1]
NAME = {4: "Mha", 2: "Gqa", 1: "Mqa"}


def write_evalset(spec):
    tok = bpe.BPETokenizer.load(str(GPT_DIR / "tokenizer.json"))
    replay = json.loads((GPT_DIR / "replay.json").read_text(encoding="utf-8"))
    live = windows(LIVE_N, story_starts=True)
    vocab = [tok.decode([i]) for i in range(spec["vocabSize"])]
    out = SITE / "src" / "lib" / "explainers" / "attention-variants" / "evalset.ts"
    lines = [
        "// attention-variants: GENERATED by pipeline/attention-variants/prepare.py (do not edit; the same set as the quantization page's).",
        "// The live evaluation set: the first 4 stories of TinyStories' validation split (TinyGPT's tokenized copy) with at least",
        "// 65 tokens, 65 tokens each (64 inputs, 64 next tokens to predict); the probe prompt (TinyGPT replay.json probe 0); the",
        "// text of every id. TinyStories by Ronen Eldan and Yuanzhi Li (2023), CDLA-Sharing-1.0.",
        f"export const EVAL_IDS: number[][] = {json.dumps(live.tolist())};",
        f"export const PROBE_TEXT = {json.dumps(replay['probes'][0])};",
        f"export const PROBE_IDS: number[] = {json.dumps(replay['probeIds'][0])};",
        f"export const VOCAB: string[] = {json.dumps(vocab, ensure_ascii=False)};",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", out)


def uptrain(spec, W0, kv, train, val, dev):
    W = {k: v.clone().requires_grad_(True) for k, v in pool_kv(W0, spec["nLayer"], spec["nHead"], kv).items()}
    decay = [v for k, v in W.items() if v.dim() == 2]
    other = [v for k, v in W.items() if v.dim() != 2]
    opt = torch.optim.AdamW([{"params": decay, "weight_decay": 0.1}, {"params": other, "weight_decay": 0.0}], lr=LR, betas=(0.9, 0.95))
    g = torch.Generator().manual_seed(0)
    curve = {}
    for step in range(STEPS + 1):
        if step in EVAL_AT:
            curve[step] = perplexity(spec, {k: v.detach() for k, v in W.items()}, val)
            print(f"  kv={kv} step {step}: val ppl {curve[step]:.4f}", flush=True)
        if step == STEPS:
            break
        lr = LR * (step + 1) / WARM if step < WARM else LR_END + 0.5 * (LR - LR_END) * (1 + math.cos(math.pi * (step - WARM) / (STEPS - WARM)))
        for grp in opt.param_groups:
            grp["lr"] = lr
        starts = torch.randint(0, train.numel() - 65, (BATCH,), generator=g)
        b = torch.stack([train[s: s + 65] for s in starts.tolist()]).to(dev)
        logits = forward(spec, W, b[:, :-1])
        loss = torch.nn.functional.cross_entropy(logits.reshape(-1, logits.shape[-1]), b[:, 1:].reshape(-1))
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(list(W.values()), 1.0)
        opt.step()
    return curve


def main():
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    torch.manual_seed(0)
    spec, W = load_tinygpt(dev)
    write_evalset(spec)
    val = windows(BIG_N).to(dev)
    train = torch.from_numpy(np.fromfile(DATA / "train.bin", dtype="<u2").astype(np.int64))
    today = datetime.date.today().isoformat()
    src = "pipeline/attention-variants/prepare.py"
    facts = {}

    def put(k, v, unit):
        facts[k] = {"value": v, "source": src, "unit": unit, "measured": today}

    put("bigTokens", BIG_N * 64, "next tokens scored (1,000 windows of the validation split)")
    put("pretrainSteps", spec["training"]["steps"], "TinyGPT's pretraining steps (spec.json training.steps)")
    put("upSteps", STEPS, "uptraining steps (5% of TinyGPT's 30,000 pretraining steps)")
    put("upTokens", STEPS * BATCH * 64, "training tokens seen while uptraining")
    t0 = time.time()
    for kv in KVS:
        curve = uptrain(spec, W, kv, train, val, dev)
        for s, p in curve.items():
            put(f"ppl{NAME[kv]}{s}", round(p, 4), f"validation perplexity with {kv} key/value head(s) per block after {s} uptraining steps")
    print(f"uptraining took {time.time() - t0:.0f} s on {dev}")
    dst = SITE / "static" / "models" / "attention-variants"
    dst.mkdir(parents=True, exist_ok=True)
    (dst / "facts.json").write_text(json.dumps({"format": "atlas-facts/1", "facts": facts}, indent=1) + "\n", encoding="utf-8", newline="\n")
    print("wrote", dst / "facts.json")


if __name__ == "__main__":
    main()
