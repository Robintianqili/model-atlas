"""masked-lm: copy the data and facts this concept page reads from the live packages (read only).

The page runs the shipped TinyBERT and TinyGPT (static/models/tinybert, static/models/tinygpt) as trace sources; it
measures nothing new. This script copies, without changing them:
  - TinyBERT's vocabulary and token flags (spec.json vocab, tokenFlags) and the example sentences of its presets
    (static/models/tinybert/presets.json: sentences written for that page in the style of TinyStories, with their
    TinyGPT token ids) into the package's generated `source_data.ts`, because the copied masked-text adapter needs them
    and a concept package cannot read another model's spec.json as its own (notes: Kit issues);
  - the measured numbers the narration quotes into static/models/masked-lm/facts.json, each with its original source.

    npm run atlas -- py pipeline/masked-lm/make_data.py      (from the lane's site/; ATLAS_SITE set)
"""
from __future__ import annotations

import json
import os
from pathlib import Path

SITE = Path(os.environ.get("ATLAS_SITE") or Path(__file__).resolve().parents[2] / "site")
STATIC = SITE / "static" / "models"
PKG = SITE / "src" / "lib" / "explainers" / "masked-lm"
OUT = STATIC / "masked-lm"
DATE = "2026-10-13"

bert = json.loads((STATIC / "tinybert" / "spec.json").read_text(encoding="utf-8"))
bfacts = json.loads((STATIC / "tinybert" / "facts.json").read_text(encoding="utf-8"))["facts"]
bpre = json.loads((STATIC / "tinybert" / "presets.json").read_text(encoding="utf-8"))
gpt = json.loads((STATIC / "tinygpt" / "spec.json").read_text(encoding="utf-8"))

stories = [{"id": p["id"], "en": p["en"], "zh": p["zh"], "text": p["text"], "ids": p["ids"], "mask": p["mask"]} for p in bpre["items"]]
ts = (
    "// masked-lm: GENERATED by pipeline/masked-lm/make_data.py (do not edit). Copies, read only: TinyBERT's vocabulary and\n"
    "// token flags (static/models/tinybert/spec.json; claims.test.ts checks they still match) and its example sentences\n"
    "// (static/models/tinybert/presets.json: written for that page in the style of TinyStories; ids from TinyGPT's tokenizer).\n"
    f"export const VOCAB: string[] = {json.dumps(bert['vocab'], ensure_ascii=True)};\n"
    f"export const FLAGS = {json.dumps(bert['tokenFlags'])};\n"
    f"export const STORIES: {{ id: string; en: string; zh: string; text: string; ids: number[]; mask: number }}[] = {json.dumps(stories, ensure_ascii=False)};\n"
)
(PKG / "source_data.ts").write_text(ts, encoding="utf-8", newline="\n")

facts: dict[str, dict] = {}
for k in ["maskRate", "maskShare", "randomShare", "keepShare", "valLoss", "valN", "valAcc", "valAccMasked", "accBoth", "accLeft", "accGpt", "cmpN", "steps", "batch"]:
    f = bfacts[k]
    facts[k] = {"value": f["value"], "unit": f["unit"], "source": f"static/models/tinybert/facts.json ({f['source']})", "measured": f["measured"]}
m = gpt["training"]["metrics"]
facts["gptValLoss"] = {"value": m["val_loss"], "unit": "nats", "source": "static/models/tinygpt/spec.json training.metrics (pipeline/tinygpt; TinyStories validation split)", "measured": gpt["parity"].get("checked", DATE)}
facts["context"] = {"value": 61, "unit": "tokens", "source": "pipeline/tinybert/data.py N_MAX (64 positions minus [CLS] and two [SEP])", "measured": DATE}
OUT.mkdir(parents=True, exist_ok=True)
(OUT / "facts.json").write_text(json.dumps({"format": "atlas-facts/1", "facts": facts}, indent=1) + "\n", encoding="utf-8", newline="\n")
print(f"wrote {PKG / 'source_data.ts'} and {OUT / 'facts.json'} ({len(facts)} facts, {len(stories)} stories)")
