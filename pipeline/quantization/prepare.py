"""quantization: the evaluation text and the measured facts of the concept page.

1. Picks the live evaluation set: the first 4 stories of TinyStories' validation split (TinyGPT's own tokenized copy,
   pipeline/data/tinystories/val.bin) that are at least 65 tokens long, 65 tokens each (64 inputs, 64 next tokens),
   plus the probe prompt "Once upon a time, there was a little" (TinyGPT's replay.json probe 0). Writes them, with the
   display text of every vocabulary id, to site/src/lib/explainers/quantization/evalset.ts (generated; do not edit).
2. Measures, in PyTorch fp32 on the GPU when there is one, the same weight-quantization configs the page runs in the
   browser, on 1,000 non-overlapping 65-token windows of the validation split (64,000 next tokens), and writes them to
   site/static/models/quantization/facts.json ({fact:<key>} in the narration).

    npm run atlas -- py pipeline/quantization/prepare.py
"""
from __future__ import annotations

import datetime
import json
import os
import sys
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tinygpt"))
from qlib import SITE, GPT_DIR, load_tinygpt, matrices, metrics, quantize, windows  # noqa: E402
import bpe  # noqa: E402

FOCUS = "L0.mlp.fc.weight"
LIVE_N, BIG_N = 4, 1000
CONFIGS = [(8, "tensor"), (8, "channel"), (8, "block"), (4, "tensor"), (4, "channel"), (4, "block")]


def main():
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    spec, W = load_tinygpt(dev)
    tok = bpe.BPETokenizer.load(str(GPT_DIR / "tokenizer.json"))
    replay = json.loads((GPT_DIR / "replay.json").read_text(encoding="utf-8"))
    live = windows(LIVE_N, story_starts=True)
    vocab = [tok.decode([i]) for i in range(spec["vocabSize"])]
    out = SITE / "src" / "lib" / "explainers" / "quantization" / "evalset.ts"
    lines = [
        "// quantization: GENERATED by pipeline/quantization/prepare.py (do not edit). The live evaluation set: the first",
        "// 4 stories of TinyStories' validation split (TinyGPT's tokenized copy) with at least 65 tokens, 65 tokens each",
        "// (64 inputs, 64 next tokens to predict); the probe prompt (TinyGPT replay.json probe 0); the text of every id.",
        "// TinyStories by Ronen Eldan and Yuanzhi Li (2023), CDLA-Sharing-1.0.",
        f"export const EVAL_IDS: number[][] = {json.dumps(live.tolist())};",
        f"export const PROBE_TEXT = {json.dumps(replay['probes'][0])};",
        f"export const PROBE_IDS: number[] = {json.dumps(replay['probeIds'][0])};",
        f"export const VOCAB: string[] = {json.dumps(vocab, ensure_ascii=False)};",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", out, [tok.decode(w[:12].tolist()) for w in live])

    big = windows(BIG_N).to(dev)
    today = datetime.date.today().isoformat()
    src = "pipeline/quantization/prepare.py"
    facts = {}

    def put(k, v, unit):
        facts[k] = {"value": v, "source": src, "unit": unit, "measured": today}

    base = metrics(spec, W, W, big)
    put("bigTokens", BIG_N * 64, "next tokens scored (1,000 windows of the validation split)")
    put("bigPpl0", round(base["ppl0"], 4), "perplexity of the fp32 model on those tokens")
    tag = {"tensor": "t", "channel": "c", "block": "b"}
    for bits, gran in CONFIGS:
        Wq = dict(W)
        for name in matrices(spec):
            Wq[name] = quantize(W[name], bits, gran)
        m = metrics(spec, W, Wq, big)
        k = f"All{bits}{tag[gran]}"
        put("ppl" + k, round(m["ppl"], 4), f"perplexity, every linear weight matrix int{bits} per {gran}")
        put("kl" + k, round(m["kl"], 5), f"mean KL(fp32 || int{bits} per {gran}) per position, nats")
        put("agree" + k, round(m["agree"], 4), "share of positions whose top-1 token matches fp32")
        print(k, m)
    for bits, gran in [(8, "tensor"), (4, "tensor"), (4, "channel"), (4, "block")]:
        Wq = dict(W)
        Wq[FOCUS] = quantize(W[FOCUS], bits, gran)
        m = metrics(spec, W, Wq, big)
        k = f"Lay{bits}{tag[gran]}"
        put("ppl" + k, round(m["ppl"], 4), f"perplexity, only {FOCUS} int{bits} per {gran}")
        print(k, m)
    dst = SITE / "static" / "models" / "quantization"
    dst.mkdir(parents=True, exist_ok=True)
    (dst / "facts.json").write_text(json.dumps({"format": "atlas-facts/1", "facts": facts}, indent=1) + "\n", encoding="utf-8", newline="\n")
    print("wrote", dst / "facts.json")


if __name__ == "__main__":
    main()
