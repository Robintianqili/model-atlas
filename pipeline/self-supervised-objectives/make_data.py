"""self-supervised-objectives: copy the facts and data this concept page reads from the live packages (read only).

The page runs the shipped TinyBERT and TinyGPT (static/models/tinybert, static/models/tinygpt) as trace sources; it
measures nothing new. This script copies, without changing them:
  - TinyBERT's vocabulary and token flags (spec.json vocab, tokenFlags) into the package's generated `source_data.ts`,
    because the copied masked-text adapter needs them and a concept package cannot read another model's spec.json as
    its own (notes: Kit issues);
  - one Quick, Draw! drawing of TinyViT's presets (static/models/tinyvit/presets.json; CC BY 4.0) for the image patch
    grid;
  - the measured numbers the narration quotes into static/models/self-supervised-objectives/facts.json, each with its
    original source.

    npm run atlas -- py pipeline/self-supervised-objectives/make_data.py      (from the lane's site/; ATLAS_SITE set)
"""
from __future__ import annotations

import json
import os
from pathlib import Path

SITE = Path(os.environ.get("ATLAS_SITE") or Path(__file__).resolve().parents[2] / "site")
STATIC = SITE / "static" / "models"
PKG = SITE / "src" / "lib" / "explainers" / "self-supervised-objectives"
OUT = STATIC / "self-supervised-objectives"
DATE = "2026-10-08"

bert = json.loads((STATIC / "tinybert" / "spec.json").read_text(encoding="utf-8"))
bfacts = json.loads((STATIC / "tinybert" / "facts.json").read_text(encoding="utf-8"))["facts"]
gpt = json.loads((STATIC / "tinygpt" / "spec.json").read_text(encoding="utf-8"))
vit = json.loads((STATIC / "tinyvit" / "presets.json").read_text(encoding="utf-8"))

house = next(c for c in vit["classes"] if c["id"] == "house")
drawing = house["items"][0]

ts = (
    "// self-supervised-objectives: GENERATED by pipeline/self-supervised-objectives/make_data.py (do not edit). Copies, read\n"
    "// only: TinyBERT's vocabulary and token flags (static/models/tinybert/spec.json; claims.test.ts checks they still match),\n"
    "// and one Quick, Draw! drawing (CC BY 4.0, Google Creative Lab) from TinyViT's presets (static/models/tinyvit/presets.json).\n"
    f"export const VOCAB: string[] = {json.dumps(bert['vocab'], ensure_ascii=True)};\n"
    f"export const FLAGS = {json.dumps(bert['tokenFlags'])};\n"
    f"export const DRAWING = {json.dumps({'cls': house['id'], 'en': house['en'], 'zh': house['zh'], 'b64': drawing['b64'], 'fileIndex': drawing.get('fileIndex')}, ensure_ascii=False)};\n"
)
(PKG / "source_data.ts").write_text(ts, encoding="utf-8", newline="\n")

facts: dict[str, dict] = {}
for k in ["accBoth", "accLeft", "accGpt", "cmpN", "maskRate", "maskShare", "randomShare", "keepShare", "valAccMasked", "valAcc", "valTop5", "steps", "batch"]:
    f = bfacts[k]
    facts[k] = {"value": f["value"], "unit": f["unit"], "source": f"static/models/tinybert/facts.json ({f['source']})", "measured": f["measured"]}
m = gpt["training"]["metrics"]
src = "static/models/tinygpt/spec.json training.metrics (pipeline/tinygpt; TinyStories validation split)"
facts["gptValLoss"] = {"value": m["val_loss"], "unit": "nats", "source": src, "measured": gpt["parity"].get("checked", DATE)}
facts["gptUniformLoss"] = {"value": m["uniform_baseline_loss"], "unit": "nats", "source": src, "measured": gpt["parity"].get("checked", DATE)}
facts["gptTokensSeen"] = {"value": gpt["training"]["tokensSeen"], "unit": "tokens", "source": "static/models/tinygpt/spec.json training.tokensSeen", "measured": gpt["parity"].get("checked", DATE)}
OUT.mkdir(parents=True, exist_ok=True)
(OUT / "facts.json").write_text(json.dumps({"format": "atlas-facts/1", "facts": facts}, indent=1) + "\n", encoding="utf-8", newline="\n")
print(f"wrote {PKG / 'source_data.ts'} and {OUT / 'facts.json'} ({len(facts)} facts)")
