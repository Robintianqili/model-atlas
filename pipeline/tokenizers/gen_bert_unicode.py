"""Generate site/src/lib/pages/tokenization/bert-unicode.ts: code points where HF tokenizers' BERT
(Rust unicode_categories tables, ~Unicode 9-10) and JavaScript (V8, Unicode 17) disagree.
Run check_bert_unicode.py first (it writes bert_unicode_exceptions.json)."""
import json, sys
from tokenizers import Tokenizer
b = Tokenizer.from_file('raw/bert-base-uncased-tokenizer.json')
js = json.load(open('js_unicode_sets.json'))
ex = json.load(open('bert_unicode_exceptions.json'))
norm = b.normalizer
jsMn = set(js['Mn']); jsC = set(js['C'])
extra_mn, extra_c = [], []
for c in list(range(0x80, 0x30000)) + list(range(0xE0000, 0xE0200)):
    if 0xD800 <= c <= 0xDFFF or 0xE000 <= c <= 0xF8FF: continue
    s = chr(c)
    if c not in jsMn and c not in jsC and norm.normalize_str('a' + s) == 'a' and norm.normalize_str(s) == '':
        # removed: either stripped as a mark or dropped as a control
        if norm.normalize_str('a' + s + 'b') == 'ab':
            (extra_c if s.isprintable() is False or True else extra_c).append(c)
print('removed by HF but neither Mn nor C in JS:', len(extra_c), [hex(x) for x in extra_c[:30]])
def ranges(cps):
    cps = sorted(set(cps)); out = []
    for c in cps:
        if out and out[-1][1] == c - 1: out[-1][1] = c
        else: out.append([c, c])
    return out
def ts(name, cps, doc):
    r = ranges(cps)
    return f'/** {doc} ({len(cps)} code points) */\nexport const {name}: [number, number][] = {json.dumps(r)};\n'
src = '/* Generated by pipeline/tokenizers/gen_bert_unicode.py. Do not edit. */\n' \
      '/* HF tokenizers (BERT normalizer and pre-tokenizer) use older Unicode tables than JavaScript.\n' \
      '   These lists make the JS WordPiece match HF exactly on characters whose category changed\n' \
      '   or that were added after those tables. */\n'
src += ts('NOT_PUNCT', ex['notPunct'], 'JS says punctuation (\p{P}); HF does not split on them')
src += ts('EXTRA_PUNCT', ex['extraPunct'], 'HF splits on them as punctuation; JS does not say \p{P}')
src += ts('NOT_MN', ex['notMn'], 'JS says nonspacing mark (\p{Mn}); HF does not strip them')
src += ts('NOT_CONTROL', ex['notControl'], 'JS says Cc/Cf/Co/Cs; HF does not remove them')
src += ts('EXTRA_REMOVED', extra_c, 'HF removes them (as a mark or control); JS says neither')
open(sys.argv[1], 'w', encoding='utf8').write(src)
print('written', len(src), 'chars')
