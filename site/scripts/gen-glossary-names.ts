/**
 * Generates src/lib/catalog/glossary-names.ts from src/lib/catalog/glossary.ts (redesign wave F, lazy glossary): the term
 * names only, { id: [en, zh] }, so a page that renders <Term> carries the names (a few KB) and loads the definitions
 * (glossary.ts, about 40 KB gzip) on the first hover, focus or tap of any term.
 *
 *   node scripts/gen-glossary-names.ts           rewrite the file
 *   node scripts/gen-glossary-names.ts --check   exit 1 when it is stale (check:catalog runs the same comparison)
 *
 * `atlas promote --apply` regenerates it after it adds glossary rows.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import type { GlossaryTerm } from '../src/lib/catalog/types.ts';

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Where the names module lives in a site folder. */
export const namesFile = (site: string): string => join(site, 'src', 'lib', 'catalog', 'glossary-names.ts');

const q = (s: string): string => `'${s.replaceAll(String.fromCharCode(92), String.fromCharCode(92, 92)).replaceAll("'", String.fromCharCode(92) + "'")}'`;
const key = (id: string): string => (/^[A-Za-z_$][\w$]*$/.test(id) ? id : q(id));

/** The source text of glossary-names.ts for these terms (LF line ends). */
export function namesSource(terms: GlossaryTerm[]): string {
	const rows = terms.map((g) => `\t${key(g.id)}: [${q(g.term.en)}, ${q(g.term.zh ?? g.term.en)}]`);
	return [
		'// Generated by scripts/gen-glossary-names.ts from glossary.ts: do not edit. Regenerate with',
		'// `node scripts/gen-glossary-names.ts` (atlas promote --apply does it; check:catalog fails when this file is stale).',
		'// <Term> shows these names and loads the definitions (glossary.ts) on the first hover, focus or tap of any term, so',
		'// no page shell carries them; only /glossary/, this generator and tests import glossary.ts.',
		'export const GLOSSARY_NAMES: Record<string, readonly [en: string, zh: string]> = {',
		rows.join(',\n'),
		'};',
		''
	].join('\n');
}

/** The glossary terms of a site folder (imports its glossary.ts). */
export async function siteTerms(site: string): Promise<GlossaryTerm[]> {
	const mod = (await import(pathToFileURL(join(site, 'src', 'lib', 'catalog', 'glossary.ts')).href)) as { GLOSSARY: GlossaryTerm[] };
	return mod.GLOSSARY;
}

/** Is the names file of `site` up to date with its glossary? (line ends ignored) */
export async function namesStale(site: string): Promise<boolean> {
	const f = namesFile(site);
	if (!existsSync(f)) return true;
	return readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== namesSource(await siteTerms(site));
}

/** Rewrite the names file of `site`; returns the number of terms. */
export async function writeNames(site: string): Promise<number> {
	const terms = await siteTerms(site);
	writeFileSync(namesFile(site), namesSource(terms));
	return terms.length;
}

if (process.argv[1] && /gen-glossary-names.ts$/.test(process.argv[1])) {
	if (process.argv.includes('--check')) {
		const stale = await namesStale(SITE);
		console.log(stale ? 'glossary-names.ts is stale: run node scripts/gen-glossary-names.ts' : 'glossary-names.ts is up to date');
		process.exit(stale ? 1 : 0);
	}
	const n = await writeNames(SITE);
	console.log(`wrote src/lib/catalog/glossary-names.ts (${n} terms)`);
}
