/** Numbers with units only, e.g. "≈11.7M", "<10 KB", "5.9 MB (fp32)": the same in every language. */
const NEUTRAL = /^[≈<≤~]?\s*[\d.,–]+\s?(k|M|KB|MB)?(\s\((fp32|fp16|q8|q4)\))?$/;

export function isLanguageNeutral(s: string): boolean {
	return NEUTRAL.test(s.trim());
}

/** A catalog technical string as a bilingual pair (Chinese from TECH_ZH; neutral strings as is). */
export function techText(s: string): I18n {
	return { en: s, zh: TECH_ZH[s] ?? s };
}
