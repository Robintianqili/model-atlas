<!--
  Input: the learner's text, its BPE tokens (ids; bytes on hover), the 64-token context limit,
  generated tokens in magenta, and an honest note about non-English text.
-->
<script lang="ts">
	import TextInputBar from '$lib/kit/TextInputBar.svelte';
	import TokenChips from '$lib/kit/TokenChips.svelte';
	import Term from '$lib/kit/Term.svelte';
	import Lang from '$lib/kit/Lang.svelte';
	import { t } from '$lib/i18n/i18n.svelte';
	import type { TokenItem } from '$lib/kit/types';
	import type { TGState } from './state.svelte';
	import { CTX } from './state.svelte';
	import { PRESETS } from './presets';

	interface Props {
		S: TGState;
		text: string;
		promptIds: number[];
		genIds: number[];
		oninput: (v: string) => void;
	}
	let { S, text = $bindable(), promptIds, genIds, oninput }: Props = $props();

	const all = $derived([...promptIds, ...genIds]);
	const dropped = $derived(Math.max(0, all.length - CTX));
	const chips = $derived<TokenItem[]>(
		S.tok
			? all.map((id, i) => ({
					text: S.tok!.tokenToDisplay(id),
					id,
					bytes: Array.from(S.tok!.tokenBytes(id)),
					special: S.tok!.isSpecial(id),
					tone: i < dropped ? 'muted' : i >= promptIds.length ? 'generated' : undefined
				}))
			: []
	);
	// the selected chip = the selected position in the window (shifted by the dropped tokens)
	let selected = $state<number | null>(null);
	$effect(() => {
		selected = S.T ? S.pos + dropped : null;
	});
	function onselect(i: number) {
		if (i < dropped) {
			selected = S.T ? S.pos + dropped : null;
			return;
		}
		S.selectPos(i - dropped);
	}
	// raw byte tokens: ids < 256 whose byte is ≥ 0x80 (a piece of a multi-byte UTF-8 character)
	const byteTokens = $derived(promptIds.filter((id) => id >= 128 && id < 256).length);
	const nonAsciiChars = $derived([...text].filter((c) => c.codePointAt(0)! > 127).length);
	const fill = $derived(Math.min(1, all.length / CTX));
</script>

<div class="inp">
	<TextInputBar
		bind:value={text}
		maxLength={400}
		multiline
		rows={2}
		label={{ en: 'Your text (the prompt)', zh: '你的文本（提示词）' }}
		placeholder={{ en: 'Type the start of a story…', zh: '输入一个故事的开头（英文）…' }}
		presets={PRESETS}
		{oninput}
	/>

	<div class="tokhead">
		<span class="lbl">{t({ en: 'What the model reads: tokens', zh: '模型读到的：词元' })}</span>
		<span class="meter" title={t({ en: 'Context window: 64 tokens', zh: '上下文窗口：64 个词元' })}>
			<span class="bar" aria-hidden="true"><span style="width: {fill * 100}%" class:full={all.length >= CTX}></span></span>
			<span class="num">{Math.min(all.length, CTX)} / {CTX}</span>
			<span class="muted">{t({ en: 'tokens in the context window', zh: '个词元在上下文窗口内' })}</span>
		</span>
	</div>
	{#if chips.length}
		<TokenChips tokens={chips} showIds bind:selected {onselect} label={{ en: 'Tokens of your text', zh: '你的文本的词元' }} />
	{:else}
		<p class="muted empty">{t({ en: 'Type something (English works best) to run the model.', zh: '输入一些文字（英文效果最好）来运行模型。' })}</p>
	{/if}
	<p class="hint muted">
		{t({
			en: 'Each chip is one token; the small number is its id (0–1023). Hover, focus or tap a chip for its bytes. Click a chip to follow that token through the model.',
			zh: '每个色块是一个词元，下方小数字是它的 id（0–1023）。悬停、聚焦或轻点可查看它的字节。点击一个词元，就能跟踪它穿过模型。'
		})}
		{#if genIds.length}
			<span class="gen-key"><span class="sw" aria-hidden="true"></span>{t({ en: 'magenta = generated by the model', zh: '品红色 = 模型生成的词元' })}</span>
		{/if}
	</p>
	{#if dropped > 0}
		<p class="note warn">
			{t({
				en: `TinyGPT can only look at the last ${CTX} tokens (its context window). The first ${dropped} are crossed out: the model does not see them.`,
				zh: `TinyGPT 只能看到最后 ${CTX} 个词元（它的上下文窗口）。前 ${dropped} 个被划掉了：模型看不到它们。`
			})}
		</p>
	{/if}

	<aside class="note" class:alert={byteTokens > 0}>
		<Lang>
			{#snippet en()}
				<strong>English only.</strong> TinyGPT was trained on English children's stories (TinyStories). Its
				<Term id="tokenizer" /> learned merges for English pieces only, so Chinese, emoji and other scripts fall back to
				raw UTF-8 bytes: one Chinese character becomes 3 byte tokens, and 我爱自然语言处理 becomes 24 tokens. The model never saw
				such bytes in training, so its predictions there are meaningless. All numbers are still computed for real.
			{/snippet}
			{#snippet zh()}
				<strong>只懂英文。</strong>TinyGPT 只用英文儿童故事（TinyStories）训练。它的<Term id="tokenizer" />只学过英文片段的合并规则，
				所以中文、emoji 和其他文字会退回到原始 UTF-8 字节：一个汉字变成 3 个字节词元，“我爱自然语言处理”变成 24 个词元。模型在训练中从没见过这些字节，所以它在这里的预测没有意义。不过所有数字仍然是真实计算出来的。
			{/snippet}
		</Lang>
		{#if byteTokens > 0}
			<span class="live-line">
				{t({
					en: `Your text: ${nonAsciiChars} non-English character${nonAsciiChars === 1 ? '' : 's'} → ${byteTokens} raw byte token${byteTokens === 1 ? '' : 's'} (ids 128–255, shown as <0x..>).`,
					zh: `你的文本：${nonAsciiChars} 个非英文字符 → ${byteTokens} 个原始字节词元（id 128–255，显示为 <0x..>）。`
				})}
			</span>
		{/if}
	</aside>
</div>

