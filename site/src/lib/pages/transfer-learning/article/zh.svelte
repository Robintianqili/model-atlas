	<p>微调大网络对<Term id="learning-rate" />很敏感。论文对每个任务尝试四个学习率（2e-5 到 5e-5），保留验证集上最好的那个。在我们的实验里，与固定的 2e-5 相比，这一搜索让 MRPC 提高 2.0 个百分点，RTE 提高 1.8 个百分点。但最优值是在报告结果的同一个验证集上挑出来的，因此论文中小任务的数字略微偏乐观。</p>
{:else if part === 'compare-small'}
	<h3>数据少时，全量微调很脆弱</h3>
	<p>
		RTE（句子 A 能推出句子 B 吗？）只有 2,490 对训练样本。我们用 Google 原版 BERT 代码里的优化器在 RTE 上微调 BERT-Large，6 次里有 4 次崩溃：它们对每一对句子都预测同一个类别，得分是
		47.3% 或 52.7%，恰好就是那个类别在验证集里的占比。原因是这个优化器省略了 Adam 的偏差校正，导致最初几步的更新最多大了约 6 倍。加上偏差校正（AdamW）后，6 次都没有崩溃，均值从 54.3% 升到 70.2%。可训练参数多、数据又少，正是训练最容易出问题的地方。
	</p>
{:else if part === 'compare-mnli'}
	<h3>中间任务训练：先 MNLI，再 RTE</h3>
	<p>
		对付小任务的另一个办法，是先在同类型的大任务上微调，再在小任务上微调，这叫中间任务训练（Phang 等人在 2018 年称之为 STILTs）。MNLI 问的几乎就是 RTE 的问题（A 能推出 B
		吗？只是答案有 3 种而不是 2 种），训练样本有 392,702 对，是 RTE（2,490 对）的 158 倍。我们的复现用和直接训练相同的 5 个种子做了这个实验：先在 MNLI 上把 BERT-base 微调 3 个
		epoch，把它的三分类输出头换成新的二分类输出头，然后完全照旧在 RTE 上微调（学习率 2e-5、3 个 epoch、批大小 32）。
	</p>
{:else if part === 'compare-mnli-after'}
	<p>
		RTE 验证集正确率从 63.0% ± 2.7 升到 <strong>77.3% ± 0.9，高了 14.3 个百分点</strong>，5 个种子全部更高，而且种子之间也更一致了（标准差从 2.7 缩小到 0.9）。这和 TinyCNN
		上的做法一样，只是高了一个层次：MNLI 的输出头被扔掉，留下来的是一个已经学会比较两句话的主体，RTE 的 2,490 对样本只需要在它上面再调一点。
	</p>
	<p>
		BERT 论文只在脚注 14 里提到这一点：作者“确实观察到，与 MNLI 一起做多任务训练能显著提升 RTE”，但没有给出数字。Phang 等人报告 BERT-base 从 68.6% 升到 79.1%；那是 20
		次重启中最好的一次，不是平均值，所以比我们 5 个种子的均值高。用其他方式组合多个任务的内容，计划放在<a href="{base}/train/multitask-intermediate/">多任务页面</a>。
	</p>
{:else if part === 'pitfalls'}
	<h3>其他陷阱</h3>
	<ul>
		<li><strong>忘掉旧任务。</strong>全量微调会改动共享的层。旧的 10 类输出头是在旧特征上训练的，微调之后它可能就不灵了，这叫灾难性遗忘。如果主体是冻结的，新输出头就和旧输出头并排放着，两者都能继续工作。</li>
		<li><strong>在测试集上调参。</strong>在要报告结果的数据上挑学习率、挑最好的种子或最好的层，会让结果看起来比实际好。要留一个单独的验证集，第 2 部分的 TinyCNN 实验就是这样做的。</li>
		<li><strong>输入的处理方式不一致。</strong>只有新输入和预训练时的输入长得像，冻结特征才有意义。这里的每张画（包括你的）都按 Quick, Draw! 的方式取景到 28 × 28。</li>
		<li><strong>只看一种数据量。</strong>“微调胜过冻结”和反过来的说法都对，只是对应不同的数据量。一定要说明用了多少样本。</li>
	</ul>
{:else if part === 'post'}
	<p>迁移学习复用预训练网络的特征。带标签的数据少时，冻结主体、训练一个小输出头：参数少，不容易过拟合，几毫秒就能训完。数据多，或者任务与预训练数据相差很远时，就解冻并微调，同时仔细选择学习率。介于两者之间时，就在验证集上把两种方法都比一比。如果你的任务很小，不妨找一个同类型的大任务先微调：对 RTE 上的 BERT 来说，先训练 MNLI 带来了 14.3 个百分点的提升。</p>
{/if}
