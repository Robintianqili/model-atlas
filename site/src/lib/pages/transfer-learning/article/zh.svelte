{:else if part === 'hook-after'}
	<p>
		模型没法说“我不知道”。它的最后一层，也就是<Term id="head">输出头</Term>，恰好有 10 个输出，<Term id="softmax" />
		把 100% 的概率分给这 10 个类别。于是大多数梯子被认成了房子（1,500 张测试梯子里占 61%），大多数信封被认成了鱼或房子。
	</p>
	<p>
		不过，网络的其余部分对梯子并非毫无用处。它的卷积层学会了识别笔画、拐角、交叉和封闭形状，而梯子恰恰就是由这些构成的。<Term id="transfer-learning" />就是把模型在一个任务上学到的东西拿到新任务上再用。本页要回答的问题是：<strong>只用几张画，能不能教会 TinyCNN 两个新类别？</strong>
	</p>
{:else if part === 'toy-intro'}
	<p>
		最简单的做法是<Term id="feature-extraction" />：把所有预训练层<Term id="frozen-layer">冻结</Term>（灰色、带锁），把旧的 10 类输出头放在一边，然后在冻结主体为每张画算出的
		256 个数上，训练一个全新的二分类输出头。新输出头只是一个<Term id="dense-layer" />：256 × 2 个权重加 2 个偏置，共 514 个可训练<Term id="parameter">参数</Term>。其余 4,152 个参数始终不变。
	</p>
	<p>
		选好每个类别用几张示例图，或者自己画，然后点<strong>训练</strong>。训练用的是最普通的全批量<Term id="gradient-descent" />，损失是<Term id="cross-entropy" />：一共
		200 步，每一步把你的所有样本过一遍，在你的浏览器里几毫秒就能跑完。留出的测试图从不参与训练。
	</p>
{:else if part === 'toy-zoom'}
	<h3>放大看：哪些被冻结，哪些在学习</h3>
	<p>点击网络中的任意一块。冻结的块会显示它对所选画作的计算结果，这些数在训练前后完全一样。新输出头会展示它的算式：两个分数各是 256 个特征的加权和。拖动上面的训练回放，你会看到只有输出头的权重在变。</p>
{:else if part === 'toy-map'}
	<h3>为什么几个样本就够了</h3>
	<p>每张画都会变成 256 维特征空间里的一个点。这张地图用 PCA（主成分分析，离线在测试图上拟合）把这个空间压成 2 维。灰色的点是 10 个已知类别的画；橙色和蓝色是两个新类别。</p>
	<p>网络从没见过梯子和信封，可它的冻结特征已经把两者放在了不同的区域。线性输出头只能画一条直的分界线（在 256 维空间里切一刀平面），而在这里，一条直线就够了。几个样本足以确定这条线的位置，所以每类只给一张图，效果也远好于瞎猜。</p>
	<p>如果两个类别在冻结特征看来很像（比如两种圆），它们的点就会重叠，任何建立在这些特征上的输出头都很难把它们分开。这时就得让特征本身改变，也就是<Term id="fine-tuning" />，见第 2 部分。</p>
{:else if part === 'real-intro'}
	<p>冻结只是一种选择。你也可以微调所有层：从预训练权重出发，接上新输出头，然后全部一起训练（4,666 个参数）。或者用同样的网络从零训练，从随机权重开始（同样 4,666 个参数）。哪种最好，主要取决于你有多少带标签的数据。</p>
	<p>我们在同一个“梯子 vs 信封”任务上离线跑了这三种方法：10 种训练集大小，每种 5 个随机种子。三者的预算相同：300 步全批量 Adam，每种方法的学习率都在单独的验证集上选定。每次运行都在 3,000 张留出的测试图上打分。</p>
{:else if part === 'real-after'}
	<p>
		每类只有 1 张图时，冻结特征 + 新输出头平均达到 93.1%。全量微调是 85.9%，从零训练是 78.7%，而且不同种子之间差别巨大：有一次从零训练只得到
		44.0%，比抛硬币还差。可训练参数越多，拟合两张图的方式就越多，其中很多是错的，这就是<Term id="overfitting" />。冻结方案只需要定 514 个数，而且起点就是已经有意义的特征。
	</p>
	<p>随着数据增多，差距逐渐缩小。从每类约 16 张开始，三者彼此相差不到 3 个百分点；全量微调要到每类 2,048 张时才超过冻结方案（98.59% 对 98.41%）。</p>
	<p>请如实地看待这个结果：对这些特征来说，梯子和信封是一对很容易区分的类别，所以曲线很早就汇合了。如果新任务和网络原来的训练内容差得更远，冻结特征的帮助会更小，微调也会更早显出优势。</p>
