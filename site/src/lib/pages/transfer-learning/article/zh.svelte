	<p>
		TinyCNN 只有 6,722 个参数。对一个 1.1 亿参数的语言模型，同样的取舍还成立吗？在我们的 BERT 复现中，我们按论文的配方（批大小 32、3 个 epoch）在 7 个 GLUE
		任务上微调了 Google 发布的 BERT-base，并检验了论文中关于微调的结论：在一块笔记本 GPU 上共做了 218 次微调。分数都是 GLUE 验证集上的结果，写成多个随机种子的均值 ± 样本标准差。
	</p>
{:else if part === 'compare-features'}
	<h3>冻结特征 vs 全量微调</h3>
	<p>
		在 SST-2 上（这条影评是正面的吗？共 67,349 个训练句子），全量微调达到 93.0% ± 0.2（3 个种子）。最好的冻结特征配上<Term id="linear-probe" />（一个逻辑回归）只有
		86.8%，低了 6.2 个百分点。这组特征取自最后四层的输出：每层先对句子里所有词元求平均，再拼接起来。在 MRPC 上（两句话意思相同吗？），差距是 8.1 个百分点：84.1% 对 76.0%。
	</p>
	<p>
		BERT 论文在命名实体识别上只发现了 0.3 F1 的差距（96.4 对 96.1）。所以，冻结的 BERT 特征确实不错，但在有几万条带标签句子时，让整个网络一起适应会更好。为了公平，有两点要说明：我们的探针只在
		SST-2 中抽样的 20,000 个句子上训练（而微调用了全部 67,349 句）；86.8% 是 27 种层与池化组合中最好的一个，而且是直接在验证集上挑出来的。
	</p>
{:else if part === 'compare-layers'}
	<p>哪一层的特征最好？越深越好。基于词元平均的探针，从第 0 层（嵌入层输出）的 77.9% 一路升到第 9、10 层的 85.4%。基于 [CLS] 向量的探针在第 0 层只有 50.9%，正好等于“总猜多数类”的基线：在经过任何注意力层之前，每个句子的 [CLS] 向量都一模一样，探针只能猜较常见的那个标签。</p>
